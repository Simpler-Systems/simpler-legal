const SKIP_DIR = new Set(['node_modules', 'target', 'dist', '.git', '.vite', 'raw', 'out']);
function walkDisk(dir, acc, rel = '') {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const r = rel ? `${rel}/${name}` : name;
    const st = statSync(p);
    if (st.isDirectory()) { if (!SKIP_DIR.has(name)) walkDisk(p, acc, r); }
    else if (!/\.log$/.test(name)) acc.push(r);
  }
  return acc;
}
