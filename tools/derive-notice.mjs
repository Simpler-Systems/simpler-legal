  pageChecks.problems = problems.length;
  // CONTROLs: each breaks the page one way, and the check must fail on it
  const edit = (from, to) => () => {
    const s = bytes.toString('latin1');
    if (!s.includes(from)) throw new Error(`the page has no "${from}" to change`);
    return [rel, Buffer.from(s.replace(from, to), 'latin1'), license, folder];
  };
  const CONTROLS = [
    ['the licence page set back to LICENSE', () => ['LICENSE', license, license, folder]],
    ['LICENSE\'s line ends turned to CRLF on the page', () => [rel, Buffer.concat([Buffer.from(license.toString('latin1').replace(/\n/g, '\r\n'), 'latin1'), bytes.subarray(license.length)]), license, folder]],
    ['one word of the Apache text changed on the page', edit('Apache License', 'Apache Licence')],
    ['the section naming vcomp140.dll, which is not in the llama folder', edit('msvcp140.dll, ', 'msvcp140.dll, vcomp140.dll, ')],
    ['the section calling libomp140.x86_64.dll Microsoft\'s', edit('msvcp140.dll, ', 'msvcp140.dll, libomp140.x86_64.dll, ')],
    ['the section without vcruntime140_1.dll', edit(' and vcruntime140_1.dll', '')],
    ['the section without its pointer to Microsoft\'s terms', edit('licenses\\msvc-runtime.txt', 'the licenses folder')],
    ['the section with a CRLF line', edit(`${PAGE_HEADING}\n`, `${PAGE_HEADING}\r\n`)],
  ];
