// ── the installer's licence page (owner rulings of 2026-09-25) ────────────────────
// The product is Apache-2.0 with no end-user licence of its own (ruling 28), and LICENSE stays
// the plain Apache-2.0 text, which is what GitHub's licence detection reads. Microsoft's terms
// for the Visual C++ runtime in the llama folder require the distributor to "require
// distributors and external end users to agree to terms that protect the Distributable Code
// at least as much as this agreement" (licenses/msvc-runtime.txt). So the page the installer
// shows (bundle.licenseFile) is LICENSE, byte for byte, followed by one section on those
// files, which the user accepts with the page's I Agree. NSIS shows the file as it is: LICENSE
// is LF-only, so the section is LF-only and plain ASCII too.
// The check fails when the page is not that file, does not begin with LICENSE's exact bytes,
// or has a section that names a file the llama folder does not hold, names one that is not
// Microsoft's, or leaves one of Microsoft's out. Its CONTROLs are run on every check.
const LICENCE_PAGE = 'app/src-tauri/installer-licence.txt';
const PAGE_HEADING = 'Microsoft Visual C++ runtime files in the llama folder';
// The llama folder's files and which of them are Microsoft's: the pins in tools/fetch-deps.mjs
// where this tree has it (a clone), else the folder on disk (the distribution tree, which
// carries llama-cuda/ and not fetch-deps.mjs).
function llamaFolder() {
  if (fileSet.has('tools/fetch-deps.mjs')) {
    const src = readFileSync(join(ROOT, 'tools/fetch-deps.mjs'), 'utf8');
    const pins = (s) => [...s.matchAll(/\[\s*'([^'/]+)',\s*'[0-9a-f]{64}',\s*\d+\s*\]/g)].map((m) => m[1]);
    const vcrt = /^const VCRT = \{[\s\S]*?^\};/m.exec(src);
    return { from: 'the files tools/fetch-deps.mjs pins for llama-cuda/', all: pins(src), microsoft: vcrt ? pins(vcrt[0]) : [] };
  }
  if (existsSync(join(ROOT, 'llama-cuda'))) {
    const all = readdirSync(join(ROOT, 'llama-cuda'));
    return { from: 'llama-cuda/', all, microsoft: all.filter((n) => MS_CRT.test(n)) };
  }
  return null;
}
function licencePageProblems(rel, page, license, folder) {
  const out = [];
  if (rel !== LICENCE_PAGE) out.push(`${CONF}: bundle.licenseFile must name ${LICENCE_PAGE} ("installer-licence.txt"), the page the installer's licence screen shows; it names ${rel ?? 'nothing'}`);
  if (!page) { out.push(`${rel ?? LICENCE_PAGE} is not in this tree`); return out; }
  if (!license) { out.push('LICENSE is not in this tree'); return out; }
  if (page.length < license.length || !page.subarray(0, license.length).equals(license)) {
    let i = 0;
    while (i < license.length && page[i] === license[i]) i++;
    out.push(`${rel} does not begin with LICENSE's exact bytes (the first difference is at byte ${i})`);
  }
  const section = page.subarray(license.length).toString('latin1');
  if (!section.includes(PAGE_HEADING)) out.push(`${rel} has no section headed "${PAGE_HEADING}" after LICENSE`);
  if (/[^\t\n\r\x20-\x7e]/.test(section)) out.push(`the section after LICENSE in ${rel} is not plain ASCII`);
  if (license.includes(13) ? /(^|[^\r])\n/.test(section) : section.includes('\r')) out.push(`the section after LICENSE in ${rel} does not use LICENSE's line endings (${license.includes(13) ? 'CRLF' : 'LF'}); NSIS shows the file as it is`);
  if (!/licenses[\\/]msvc-runtime\.txt/.test(section)) out.push(`the section after LICENSE in ${rel} does not say where Microsoft's terms are (licenses\\msvc-runtime.txt)`);
  if (!folder) { out.push('no list of the llama folder to check the section against: this tree has neither tools/fetch-deps.mjs nor llama-cuda/'); return out; }
  if (!folder.microsoft.length) out.push(`${folder.from} names no Microsoft file to check the section against`);
  const named = [...new Set([...section.matchAll(/[A-Za-z0-9_.-]+\.dll\b/gi)].map((m) => m[0]))];
  for (const n of named) {
    if (!folder.all.some((f) => f.toLowerCase() === n.toLowerCase())) out.push(`the section after LICENSE in ${rel} names ${n}, which is not in the llama folder (${folder.from})`);
    else if (!folder.microsoft.some((f) => f.toLowerCase() === n.toLowerCase())) out.push(`the section after LICENSE in ${rel} names ${n} as Microsoft's; the llama folder's Microsoft files are ${folder.microsoft.join(', ')}`);
  }
  for (const m of folder.microsoft) if (!named.some((n) => n.toLowerCase() === m.toLowerCase())) out.push(`the section after LICENSE in ${rel} leaves out ${m}, a Microsoft file in the llama folder`);
  return out;
}
