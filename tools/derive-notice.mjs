// ── the licence texts of the code compiled into the app (--deps writes them) ─────────
// The app's executable links Rust crates, and the window's bundle carries npm packages. Their
// licence texts go in licenses/ with the rest of what the installer carries. --deps rewrites
// the two files from `cargo metadata` (needs cargo and the crates in its local registry) and
// app/frontend/node_modules (needs `npm ci` there); a check reads only the lockfiles, so it
// runs anywhere and fails when a lockfile has changed since the files were written.
const DEP = {
  rust: { file: 'licenses/rust-crates.txt', lock: 'app/src-tauri/Cargo.lock', kind: 'crate' },
  npm: { file: 'licenses/npm-packages.txt', lock: 'app/frontend/package-lock.json', kind: 'package' },
};
const LICENSE_NAME = /^(licen[cs]es?|copying|notice|unlicense|copyright)([-._].*)?$/i;
const hashText = (t) => createHash('sha256').update(t).digest('hex');
function licenceTexts(dir) {
  const out = [];
  for (const n of readdirSync(dir).sort()) {
    if (!LICENSE_NAME.test(n)) continue;
    const p = join(dir, n);
    if (statSync(p).isFile()) out.push([n, readFileSync(p, 'utf8').replace(/\r\n/g, '\n')]);
    else for (const m of readdirSync(p).sort()) if (statSync(join(p, m)).isFile()) out.push([`${n}/${m}`, readFileSync(join(p, m), 'utf8').replace(/\r\n/g, '\n')]);
  }
  return out;
}
const lockLine = (key) => `Generated by \`node tools/derive-notice.mjs --deps\` from ${DEP[key].lock}\n(sha256 ${createHash('sha256').update(readFileSync(join(ROOT, DEP[key].lock))).digest('hex')}). Line endings are\nwritten as LF; the words are the files' own.`;
// licenses/README.md records each file's sha256 in its table; rewrite the row of each file named
function recordSha(names, why) {
  const readmePath = join(ROOT, 'licenses', 'README.md');
  let readme = readFileSync(readmePath, 'utf8');
  for (const name of names) {
    const h = createHash('sha256').update(readFileSync(join(ROOT, 'licenses', name))).digest('hex');
    const next = readme.replace(new RegExp('^(\\| `' + name.replace(/[.]/g, '\\.') + '` \\|.*\\| `)[0-9a-f]{64}(` \\|\\s*)$', 'm'), `$1${h}$2`);
    if (next === readme && !readme.includes(h)) { console.error(`${why}: licenses/README.md has no row for ${name}`); process.exit(2); }
    readme = next;
  }
  writeFileSync(readmePath, readme);
}
function renderDeps(kind, title, intro, items, generated) {
  const texts = new Map();
  const rows = items.map((it) => {
    const refs = it.texts.map(([file, text]) => {
      const h = hashText(text);
      if (!texts.has(h)) texts.set(h, { id: `T${String(texts.size + 1).padStart(3, '0')}`, text, users: [] });
      const t = texts.get(h);
      t.users.push(`${it.name} ${it.version} (${file})`);
      return `${t.id} ${file}`;
    });
    return `${kind} ${it.name} ${it.version}  [${it.license || 'no licence field'}]  ${refs.length ? refs.join(', ') : `no licence file in the published ${kind}${it.repository ? `; source: ${it.repository}` : ''}${it.authors ? `; authors: ${it.authors}` : ''}`}${it.note ? `\n    (${it.note})` : ''}`;
  });
  const bar = (s, c) => c.repeat(s.length);
  return `${title}\n${bar(title, '=')}\n\n${intro}\n\n${generated}\n\n${items.length} ${kind}s, ${texts.size} distinct licence texts.\n\n${rows.join('\n')}\n\n${[...texts.values()].map((t) => `${'-'.repeat(78)}\n${t.id}, the text of: ${t.users.join('; ')}\n${'-'.repeat(78)}\n\n${t.text.replace(/\s+$/, '')}\n`).join('\n')}`;
}
// Crates that carry prebuilt binaries. A crate whose package holds a .lib, .dll, .a, .o, .obj
// or .exe must be named here, or --deps fails: what such a file links into the app is not the
// crate's own source and its licence is not the crate's. windows_x86_64_msvc carries import
// libraries only (the names of Windows' own DLL functions, no code). webview2-com-sys carries
// Microsoft's WebView2 loader, and its build links WebView2LoaderStatic.lib into the app; the
// sha256 is that file's in the NuGet package the licence was copied from.
const PREBUILT = {
  windows_x86_64_msvc: { files: /^lib\/windows\.[0-9.]+\.lib$/ },
  'webview2-com-sys': {
    files: /^(x64|x86|arm64)[\\/](WebView2Loader\.dll|WebView2Loader\.dll\.lib|WebView2LoaderStatic\.lib)$/,
    linked: 'x64/WebView2LoaderStatic.lib', sha256: '0659b741bde6348d4c4a6ec4ceb9af50e3d0048ed9cd3c8659bccbb61fde55ee',
    note: "its build links x64/WebView2LoaderStatic.lib, Microsoft's WebView2 loader from the NuGet\n    package Microsoft.Web.WebView2 1.0.3650.58, into the app's executable; that\n    library's licence is licenses/Microsoft.Web.WebView2-LICENSE.txt, and the\n    package's notices file is licenses/Microsoft.Web.WebView2-NOTICE.txt",
  },
};
const binariesIn = (dir, rel = '') => readdirSync(join(dir, rel)).flatMap((n) => {
  const r = rel ? `${rel}/${n}` : n;
  return statSync(join(dir, r)).isDirectory() ? binariesIn(dir, r) : /\.(lib|dll|a|o|obj|exe)$/i.test(n) ? [r] : [];
});
