// derive-notice.mjs — NOTICE is DERIVED from the tree it describes, never copied between
// trees (the dev repository and the distributable tree ship different third-party material:
// the download tree carries a llama.cpp build and a Node runtime, the repository carries
// the website fonts and the benchmark corpus). Every line names files that exist; every
// third-party-looking file has a line. Either failing fails the run.
//
//   node tools/derive-notice.mjs [--root <dir>] [--write] [--deps] [--webui <llama.cpp checkout>]
//
// check (default): derive NOTICE for the tree at --root (this repository when omitted),
//   compare it with the NOTICE on disk, check every path THIRD_PARTY_NOTICES.md names and
//   the counts it states, check that the installer configuration still carries the notices
//   and licenses/ (whose files must match licenses/README.md's sha256 list) and that its
//   licence page is LICENSE byte for byte followed by the section on Microsoft's files in
//   the llama folder (with CONTROLs that must fail), and exit 1 on any difference or any
//   unaccounted file.
// --write: write the derived NOTICE, then run the same checks.
// --deps: first rewrite licenses/rust-crates.txt and licenses/npm-packages.txt (the licence
//   texts of the crates and npm packages the app is compiled from) and their sha256 in
//   licenses/README.md. Needs cargo and app/frontend/node_modules; a check does not.
// --webui <dir>: first rewrite licenses/llama.cpp-webui-npm-packages.txt, the licence texts
//   of the npm packages in the web page llama-server.exe carries, and its sha256 in
//   licenses/README.md. <dir> is a llama.cpp checkout at the commit llama-cuda/ was built
//   from, with `npm ci` run in its tools/ui. The run builds that page with the checkout's own
//   configuration, fails unless each built file occurs whole in llama-cuda/llama-server.exe,
//   and lists every package the build kept code from or read a style or font file from.
//
// The inventory is `git ls-files` (tracked, plus untracked files git does not ignore: what a
// commit of this working tree would carry) when the root is a git checkout — a clone is what
// the repository's NOTICE describes, so files on disk that are gitignored (the llama.cpp
// build in llama-cuda/, the Node sidecar, OCR language data) do not count — and a walk of
// the disk otherwise (the distributable tree has no git; what is there ships).
